export const regionBySlug = new Map(regions.map((r) => [r.slug, r]))

export function getRegion(slug: string): Region | undefined {
  return regionBySlug.get(slug)
}

export function getRegionCard(regionSlug: string, cardSlug: string) {
  const region = getRegion(regionSlug)
  if (!region) return undefined
  const card = region.cards.find((c) => c.slug === cardSlug)
  if (!card) return undefined
  return { region, card }
}

export const availableRegions = regions.filter((r) => r.status === 'available')

/**
 * Главный призыв к действию сайта. Пока запущен один регион — ведёт прямо на
 * его карту; когда регионов станет больше, автоматически переключится на
 * страницу выбора региона.
 */
export const primaryCta = (() => {
  const region = availableRegions[0]
  const card = region?.cards.find((c) => c.status === 'available')
  if (availableRegions.length === 1 && region && card) {
    return { href: `/${region.slug}/${card.slug}`, label: 'Смотреть карту' }
  }
  return { href: '/regions', label: 'Выбрать регион' }
})()
